exports.opts = { w: 480, h: 300 };
exports.run = async (page, h) => {
  await h.boot();
  await page.evaluate(() => { S.q = 'low'; applyQuality(); });
  await h.start();
  await h.noRender();
  const result = await page.evaluate(async () => {
    const checks = [];
    const check = (ok, name) => { if (!ok) throw new Error(name); checks.push(name); };
    await PM.loadLight();

    const root = new THREE.Group();
    root.position.set(12000, 300, 12000);
    scene.add(root);
    let ownerHits = 0;
    WAR.reg(() => [{ id: 'plane-mechanics', pos: root.position, r: 5, kill: () => ownerHits++ }]);
    PLN.missile({ id: 'mechanics', root, yaw: 0, pitch: 0, v: 0, msl: 1 });
    const shot = PLN.tr[PLN.tr.length - 1];
    shot.custom(.01);
    check(ownerHits === 0 && PLN.tr.includes(shot), 'fighter missile ignores its aircraft on launch');
    check(WAR.airHit(root.position, 2, 'plane-mechanics') === null, 'air-hit owner filter');
    WAR.boom(root.position.x, root.position.y, root.position.z, 3, 'plane-mechanics');
    check(ownerHits === 0, 'blast owner filter');
    WAR.sources.pop();
    scene.remove(shot.m);
    PLN.tr.splice(PLN.tr.indexOf(shot), 1);
    scene.remove(root);

    const oldGun = { armed: GUN.armed, down: GUN.down, cd: GUN.cd, w: GUN.w };
    const oldHeli = HELI.on;
    HELI.on = true;
    GUN.armed = true;
    GUN.down = false;
    GUN.cd = 0;
    GUN.w = WEAPONS.findIndex(w => w.rocket && !w.nuke);
    const rocketIndex = GUN.rockets.length;
    GUN.fire();
    const rocket = GUN.rockets[rocketIndex];
    check(rocket && rocket.owner === 'heli-me', 'helicopter-fired rocket records its owning airframe');
    check(WAR.airHit(HELI.root.position, .6, rocket.owner) === null, 'helicopter-fired rocket ignores its airframe');
    scene.remove(rocket.mesh);
    GUN.rockets.splice(rocketIndex, 1);
    Object.assign(GUN, oldGun);
    HELI.on = oldHeli;

    const wall = AIRP.P(55, 190), wallY = AIRP.y0 + 2;
    check(insideAny(wall[0], wall[1], .1, wallY), 'airport terminal wall has a collider');
    const resolved = collide(wall[0], wall[1], .92, wallY);
    check(!insideAny(resolved[0], resolved[1], .92, wallY), 'player and car collision resolver exits airport wall');
    const tower = AIRP.P(125, 225);
    check(insideAny(tower[0], tower[1], .2, AIRP.y0 + 20), 'airport tower collider covers its upper structure');
    const hangar = AIRP.P(-190, 226);
    check(insideAny(hangar[0], hangar[1], .2, AIRP.y0 + 6), 'airport hangar back wall has a collider');

    const heliWasOn = HELI.on, heliPos = HELI.root.position.clone(), heliYaw = HELI.yaw;
    const yaw = AIRP.yawOf(0, 1), start = AIRP.P(60, 184);
    HELI.on = true;
    HELI.root.position.set(start[0], AIRP.y0 + 3, start[1]);
    HELI.velocity.set(0, 0, 0);
    HELI.yaw = yaw;
    cam.yaw = yaw;
    inp.k.KeyW = true;
    HELI.update(.1);
    inp.k.KeyW = false;
    check(Math.hypot(HELI.root.position.x - start[0], HELI.root.position.z - start[1]) < .7, 'helicopter stops at the terminal wall');
    HELI.on = heliWasOn;
    HELI.root.position.copy(heliPos);
    HELI.yaw = heliYaw;
    HELI.root.visible = heliWasOn;

    const plane = new Plane('light');
    plane.root.position.set(10, 20, 30);
    plane.root.rotation.set(.2, .8, -.25, 'YXZ');
    plane.root.updateMatrixWorld(true);
    const expected = plane.passengerSeat.clone().applyMatrix4(plane.root.matrixWorld);
    const seated = PASS.seatXform(plane.root, 0, new THREE.Vector3(), new THREE.Quaternion());
    check(seated.distanceTo(expected) < 1e-5, 'plane passenger follows the full aircraft transform');
    const peer = { peer: 'n:plane', st: { m: 'sit', pl: [0, 0, 0, 0, 0, 0, 0, 1, 1] }, plane: { root: plane.root } };
    check(PASS.hostObj(peer).kind === 'plane' && PASS.freeSeat(peer) === 0, 'co-op passenger can board a piloted plane');
    const oldPlane = PLN.cur, oldMe = COOP.myId;
    PLN.cur = plane;
    COOP.myId = 'n:me';
    check(PASS.hostRoot({ pp: COOP.myId }) === plane.root, 'co-op pilot exposes the local plane to passengers');
    PLN.cur = oldPlane;
    COOP.myId = oldMe;
    scene.remove(plane.root);
    return checks;
  });
  console.log('mechanics', JSON.stringify(result));
};
