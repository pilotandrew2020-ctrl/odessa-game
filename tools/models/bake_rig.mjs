import {chromium} from 'playwright';
import fs from 'fs';
const [ang,fwd,outp]=process.argv.slice(2);
const b=await chromium.launch({args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
const p=await b.newPage();p.on('console',m=>console.log('console',m.text().slice(0,200)));p.on('pageerror',e=>console.log('pageerr',e.message));
await p.goto('http://localhost:8766/bake_rig.html');
const r=await p.evaluate(([a,f])=>bakeRig('up/booba_cartoon.glb',+a,+f),[ang,fwd]);
for(const m of r.meshes)console.log(m.name,m.skinned,m.mat,m.pos.length/3,'verts');
for(const bn of r.bones)console.log(bn.name,'<-',bn.parent,bn.s.map(v=>+v.toFixed(2)).join(','));
fs.writeFileSync(outp,JSON.stringify(r));await b.close();
